/**
 * 목록 카드의 요약을 읽을 수 있는 한 줄 텍스트로 바꾼다.
 *
 * <p>요약은 본문 앞부분을 그대로 잘라 온 마크다운이다. 본문이 이미지로 시작하면
 * 카드에 `![스크린샷.png](/uploads/a1b2.png)` 가 글자로 나온다. 파일명과 주소가
 * 요약 자리를 차지할 뿐 아니라, 그 이미지는 이미 카드 위쪽에 썸네일로 보이고 있다.
 *
 * 결정      : 화면에 그릴 때 기호를 걷어낸다.
 * 이유      : 요약을 만드는 쪽은 서버이고, 이미 쌓인 글의 요약에도 같은 기호가
 *             들어 있다. 저장 시점에 고치면 앞으로 쓸 글만 깨끗해진다.
 * 대안      : 저장할 때 정리해서 보낸다 / 서버가 요약을 만들 때 정리한다.
 * 트레이드오프: 목록을 그릴 때마다 문자열을 훑는다.
 * 선택 이유  : 한 페이지에 10건 남짓이고 요약은 200자로 제한돼 있어 비용이 없는
 *             수준이다. 서버가 요약을 정리해 주게 되면 이 함수는 아무것도 바꾸지
 *             않고 그대로 통과시킨다.
 *
 * <p>이미지는 통째로 버리고, 링크는 보이던 글자만 남긴다. 나머지 기호(제목, 인용,
 * 목록, 강조, 인라인 코드)도 함께 걷어낸다. 이미지만 지우면 `## 배경` 같은 머리가
 * 그대로 남아, 고치다 만 것처럼 보인다.
 */
export function toPlainExcerpt(excerpt?: string | null): string {
  if (!excerpt) {
    return '';
  }

  return (
    excerpt
      // 이미지가 링크보다 먼저다. 순서를 바꾸면 느낌표만 덩그러니 남는다.
      .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
      .replace(/!\[[^\]]*\]\[[^\]]*\]/g, ' ')
      // 링크는 주소를 버리고 읽던 글자만 남긴다.
      .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
      .replace(/\[([^\]]*)\]\[[^\]]*\]/g, '$1')
      // 붙여넣기로 섞여 들어온 HTML.
      .replace(/<[^>]*>/g, ' ')
      // 코드 울타리는 줄째로 버린다. 안쪽 코드는 글자로 남겨 요약이 비지 않게 한다.
      .replace(/^\s*(?:```|~~~).*$/gm, ' ')
      // 줄머리 기호: 제목, 인용, 목록.
      .replace(/^\s{0,3}(?:#{1,6}|>+|[-*+]|\d+[.)])\s+/gm, '')
      // 구분선.
      .replace(/^\s{0,3}([-*_])(?:\s*\1){2,}\s*$/gm, ' ')
      // 강조. 홑밑줄(_)은 건드리지 않는다. snake_case 를 쓰는 글에서 식별자가
      // 조용히 망가지는 쪽이, 기울임 기호가 한 번 보이는 쪽보다 나쁘다.
      .replace(/(\*\*|__)(.*?)\1/g, '$2')
      .replace(/\*(.*?)\*/g, '$1')
      .replace(/~~(.*?)~~/g, '$1')
      .replace(/`+([^`]*)`+/g, '$1')
      // 카드에서 두 줄로 잘리므로 줄바꿈은 의미가 없다. 공백을 한 칸으로 모은다.
      .replace(/\s+/g, ' ')
      .trim()
  );
}
